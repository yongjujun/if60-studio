def _molecule(name, atoms, palette1=("#4a7be0",), palette2=("#ffffff",)):
    m = Model(name, list(palette1), list(palette2))
    for (x, y, z), r, color in atoms:
        m.sphere((x, y + 0.12, z), r, color, voxel=r / 4.0)
    return m


