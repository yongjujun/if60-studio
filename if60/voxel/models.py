MODELS = {"person": person, "cat": cat, "dog": dog, "car": car, "train": train_car,
          "tree": tree, "astronaut": astronaut, "bed": bed}


def get(name: str) -> Model:
    if name not in MODELS:
        raise ValueError(f"알 수 없는 모델: {name} (가능: {', '.join(MODELS)})")
    return MODELS[name]()
